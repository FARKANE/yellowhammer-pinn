"""
Identification check on synthetic data generated by a KNOWN source-sink model
(tests/synthetic.py).  Compares, against the true coefficients:

  v1           version-1 pipeline (logistic reaction, BC only at t=0.5, ...)
  recommended  corrected protocol + source-sink reaction, H derived from u_GLM
  recommended_cov  same with the covariate-only habitat index used to generate the data
  output-error baseline (classical, finite-volume solver + autodiff)

    python tests/synthetic_identification.py --data synth_data --out synth_out
"""
import argparse
import json
import os
import sys
import time

import numpy as np
import torch

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))

import diagnostics as dg                                     # noqa: E402
from forward_solver import FVSolver, fit_output_error        # noqa: E402
from habitat_field import HabitatField                       # noqa: E402
from pinn_yellowhammer import Trainer, v1_config, recommended_config, write_json  # noqa: E402

MODERATE = dict(n_collocation=4000, n_ic=1500, n_boundary=800, n_glm=20000,
                layers=(3, 64, 64, 64, 1), fourier_m=32, fourier_sigma=3.0,
                adam_steps=3000, lbfgs_steps=200, res_ramp_steps=600, device="cpu")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default="synth_data")
    ap.add_argument("--out", default="synth_out")
    ap.add_argument("--adam-steps", type=int, default=MODERATE["adam_steps"])
    ap.add_argument("--only", nargs="*", default=None)
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    truth = json.load(open(os.path.join(a.data, "truth.json")))["params"]
    files = dict(u_mat=os.path.join(a.data, "u_GLM_2002_2024.mat"), map_mat=os.path.join(a.data, "Map_France.mat"),
                 csv=os.path.join(a.data, "Yellowhammer_2002_2024.csv"))
    hab = os.path.join(a.data, "H_covariates_2002_2024.mat")
    mod = dict(MODERATE, adam_steps=a.adam_steps)
    cases = {
        "v1": v1_config(**files, **mod),
        "recommended": recommended_config(**files, **mod),
        "recommended_cov": recommended_config(**files, habitat_mat=hab, **mod),
    }
    results = {"truth": truth}
    for name, cfg in cases.items():
        if a.only and name not in a.only:
            continue
        t0 = time.time()
        tr = Trainer(cfg)
        tr.train(verbose=False)
        mb = dg.mass_balance_report(tr)
        fv, solver, sim, pinn = dg.forward_validation(tr, coarsen=2)
        res = dict(minutes=(time.time() - t0) / 60, params=tr.physical_params(), test=tr.val_glm_metrics(),
                   mass_balance=mb["cumulative"], dense_residual=tr.dense_residual_stats(5000),
                   forward=fv["simulation_all"]["pooled"], pinn_cells=fv["pinn_all"]["pooled"],
                   lambda1_2002=solver.principal_eigenvalue(fv["params"], 2002),
                   lambda1_2024=solver.principal_eigenvalue(fv["params"], 2024))
        results[name] = res
        write_json(results, os.path.join(a.out, "synthetic_identification.json"))
        print(f"\n[{name}] {res['minutes']:.1f} min  test R2={res['test']['r2']:.3f}  "
              f"forward-sim R2={res['forward']['r2']:.3f}")
        print("   params:", {k: round(float(v), 4) for k, v in res["params"].items()})
        c = res["mass_balance"]
        print("   cumulative change {:+.3f} = reaction {:+.3f} + diffusion {:+.3f} + residual {:+.3f}".format(
            c["dU_dt"], c["reaction"], c["diffusion"], c["residual"]))

    if not a.only or "oe" in a.only:
        hf = HabitatField(files["u_mat"], files["map_mat"], habitat_mat=hab)
        solver = FVSolver(hf, coarsen=2, reaction="source_sink")
        t0 = time.time()
        oe = fit_output_error(solver, n_adam=150, lr=0.08, n_lbfgs=20, verbose=False)
        with torch.no_grad():
            sim = solver.simulate(oe["params"])
        results["output_error"] = dict(params=oe["params"], objective=oe["objective"], minutes=(time.time() - t0) / 60,
                                       fit=solver.metrics(sim)["pooled"])
        print(f"\n[output-error] {results['output_error']['minutes']:.1f} min  R2={results['output_error']['fit']['r2']:.3f}")
        print("   params:", {k: round(v, 4) for k, v in oe["params"].items()})
        write_json(results, os.path.join(a.out, "synthetic_identification.json"))
    print("\ntruth:", truth)


if __name__ == "__main__":
    main()
